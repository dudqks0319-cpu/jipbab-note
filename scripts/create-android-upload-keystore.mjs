// 이 파일은 Play Store 업로드 서명용 keystore와 로컬 env 파일을 생성합니다.
import { randomBytes } from "node:crypto";
import { chmodSync, existsSync, mkdirSync, unlinkSync, writeFileSync } from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";

const cwd = process.cwd();
const secretsDir = path.join(cwd, ".release-secrets");
const keystorePath = path.join(secretsDir, "android-upload.jks");
const envPath = path.join(cwd, ".env.android-signing.local");
const alias = "jipbab-note-upload";
const force = process.argv.includes("--force");
const keytoolCandidates = [
  "/opt/homebrew/opt/openjdk@21/bin/keytool",
  "/opt/homebrew/opt/openjdk/bin/keytool",
  "keytool",
];

function secret() {
  return randomBytes(32).toString("base64url");
}

function firstExistingCommand(candidates) {
  for (const candidate of candidates) {
    if (candidate.includes("/") && existsSync(candidate)) {
      return candidate;
    }
    if (!candidate.includes("/")) {
      return candidate;
    }
  }

  return "keytool";
}

if ((existsSync(keystorePath) || existsSync(envPath)) && !force) {
  console.error(
    [
      "Android upload signing files already exist.",
      `- ${path.relative(cwd, keystorePath)}`,
      `- ${path.relative(cwd, envPath)}`,
      "Use --force only if you intentionally want to replace the upload key candidate.",
    ].join("\n"),
  );
  process.exit(1);
}

mkdirSync(secretsDir, { recursive: true, mode: 0o700 });
chmodSync(secretsDir, 0o700);

const storePassword = secret();
const keyPassword = storePassword;
const keytool = firstExistingCommand(keytoolCandidates);

if (force) {
  for (const filePath of [keystorePath, envPath]) {
    if (existsSync(filePath)) {
      unlinkSync(filePath);
    }
  }
}
const result = spawnSync(
  keytool,
  [
    "-genkeypair",
    "-v",
    "-storetype",
    "PKCS12",
    "-keystore",
    keystorePath,
    "-alias",
    alias,
    "-keyalg",
    "RSA",
    "-keysize",
    "4096",
    "-validity",
    "10000",
    "-storepass",
    storePassword,
    "-keypass",
    keyPassword,
    "-dname",
    "CN=JipbabNote Upload, OU=Release, O=JipbabNote, L=Seoul, ST=Seoul, C=KR",
  ],
  {
    cwd,
    encoding: "utf8",
  },
);

if (result.error || result.status !== 0) {
  console.error("Failed to create Android upload keystore.");
  if (result.error) {
    console.error(result.error.message);
  }
  if (result.stderr) {
    console.error(result.stderr);
  }
  process.exit(result.status ?? 1);
}

chmodSync(keystorePath, 0o600);
writeFileSync(
  envPath,
  [
    "# Generated by scripts/create-android-upload-keystore.mjs",
    "# Keep this file and .release-secrets/android-upload.jks private and backed up.",
    `ANDROID_UPLOAD_KEYSTORE_PATH=${keystorePath}`,
    `ANDROID_UPLOAD_KEYSTORE_PASSWORD=${storePassword}`,
    `ANDROID_UPLOAD_KEY_ALIAS=${alias}`,
    `ANDROID_UPLOAD_KEY_PASSWORD=${keyPassword}`,
    "",
  ].join("\n"),
  {
    encoding: "utf8",
    mode: 0o600,
  },
);
chmodSync(envPath, 0o600);

const verify = spawnSync(
  keytool,
  ["-list", "-keystore", keystorePath, "-storepass", storePassword, "-alias", alias],
  {
    cwd,
    encoding: "utf8",
  },
);

if (verify.error || verify.status !== 0) {
  console.error("Created keystore, but keytool verification failed.");
  process.exit(verify.status ?? 1);
}

console.log("Android upload keystore candidate created.");
console.log(`- keystore: ${path.relative(cwd, keystorePath)}`);
console.log(`- env file: ${path.relative(cwd, envPath)}`);
console.log("- passwords were written only to the ignored env file and were not printed");
