// 이 파일은 저장소 바이너리의 크기, 중복, 참조 상태를 결정적으로 감사합니다.
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const BINARY_EXTENSIONS = new Set([
  ".aab", ".avif", ".gif", ".ipa", ".jpeg", ".jpg", ".mov", ".mp4", ".pdf", ".png", ".webp", ".zip",
]);
const FORBIDDEN_ARCHIVE_EXTENSIONS = new Set([".aab", ".ipa", ".zip"]);
const MAX_BINARY_BYTES = 5 * 1024 * 1024;
const reportPath = "docs/repository-binary-inventory.md";
const shouldWrite = process.argv.includes("--write");

function repositoryFiles() {
  return execFileSync("git", ["ls-files", "--cached", "--others", "--exclude-standard", "-z"], {
    encoding: "utf8",
  }).split("\0").filter(Boolean).sort();
}

const files = repositoryFiles();
const binaries = files
  .filter((file) => BINARY_EXTENSIONS.has(path.extname(file).toLowerCase()))
  .filter((file) => existsSync(file))
  .map((file) => {
    const buffer = readFileSync(file);
    return {
      file,
      bytes: buffer.byteLength,
      extension: path.extname(file).toLowerCase(),
      sha256: createHash("sha256").update(buffer).digest("hex"),
    };
  });

const textCorpus = files
  .filter((file) => file !== reportPath)
  .filter((file) => !BINARY_EXTENSIONS.has(path.extname(file).toLowerCase()))
  .filter((file) => existsSync(file))
  .map((file) => {
    try {
      return readFileSync(file, "utf8");
    } catch {
      return "";
    }
  })
  .join("\n");

const duplicateGroups = [...Map.groupBy(binaries, (item) => item.sha256).values()]
  .filter((items) => items.length > 1)
  .sort((left, right) => right[0].bytes - left[0].bytes);
const unreferencedImages = binaries
  .filter((item) => item.file.startsWith("public/images/"))
  .filter((item) => {
    const publicPath = item.file.slice("public".length);
    return !textCorpus.includes(item.file) && !textCorpus.includes(publicPath);
  });
const oversized = binaries.filter((item) => item.bytes > MAX_BINARY_BYTES);
const forbiddenArchives = binaries.filter((item) => FORBIDDEN_ARCHIVE_EXTENSIONS.has(item.extension));
const totalBytes = binaries.reduce((total, item) => total + item.bytes, 0);
const largest = [...binaries].sort((left, right) => right.bytes - left.bytes).slice(0, 25);

function formatBytes(bytes) {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 ** 2) return `${(bytes / 1024).toFixed(1)} KiB`;
  return `${(bytes / 1024 ** 2).toFixed(2)} MiB`;
}

function buildReport() {
  const lines = [
    "# Repository binary inventory",
    "",
    "> Generated by `pnpm audit:repository-binaries --write`. This report does not rewrite Git history or delete assets.",
    "",
    "## Summary",
    "",
    `- Binary files: ${binaries.length}`,
    `- Total binary bytes: ${totalBytes} (${formatBytes(totalBytes)})`,
    `- Duplicate hash groups: ${duplicateGroups.length}`,
    `- Unreferenced public images: ${unreferencedImages.length}`,
    `- Files over ${formatBytes(MAX_BINARY_BYTES)}: ${oversized.length}`,
    `- Tracked release archives: ${forbiddenArchives.length}`,
    "",
    "## Largest files",
    "",
    "| Bytes | Size | Path |",
    "| ---: | ---: | --- |",
    ...largest.map((item) => `| ${item.bytes} | ${formatBytes(item.bytes)} | \`${item.file}\` |`),
    "",
    "## Duplicate hashes",
    "",
    ...(duplicateGroups.length === 0
      ? ["No duplicate binary hashes found."]
      : duplicateGroups.flatMap((items) => [
          `- \`${items[0].sha256}\` · ${formatBytes(items[0].bytes)} each`,
          ...items.map((item) => `  - \`${item.file}\``),
        ])),
    "",
    "## Unreferenced public images",
    "",
    ...(unreferencedImages.length === 0
      ? ["No unreferenced public images found by exact path scan."]
      : unreferencedImages.map((item) => `- \`${item.file}\``)),
    "",
    "## Policy",
    "",
    `- A single repository binary must not exceed ${formatBytes(MAX_BINARY_BYTES)}.`,
    "- IPA, AAB, and ZIP release artifacts must remain outside Git.",
    "- Duplicate and unreferenced findings are review queues; this command never deletes files.",
    "- Image rights and source approval remain governed by the recipe source and human-review manifests.",
    "",
  ];
  return lines.join("\n");
}

const report = buildReport();
if (shouldWrite) writeFileSync(reportPath, report, "utf8");

console.log("Repository binary audit");
console.log(`Binary files: ${binaries.length}`);
console.log(`Total: ${formatBytes(totalBytes)}`);
console.log(`Duplicate hash groups: ${duplicateGroups.length}`);
console.log(`Unreferenced public images: ${unreferencedImages.length}`);
console.log(`Oversized binaries: ${oversized.length}`);
console.log(`Forbidden release archives: ${forbiddenArchives.length}`);

if (!shouldWrite && (!existsSync(reportPath) || readFileSync(reportPath, "utf8") !== report)) {
  console.error(`Binary inventory is stale. Run: pnpm audit:repository-binaries --write`);
  process.exit(1);
}
if (oversized.length > 0 || forbiddenArchives.length > 0) process.exit(1);
